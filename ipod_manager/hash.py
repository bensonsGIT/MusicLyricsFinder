# ── public API ─────────────────────────────────────────────────────────────

def apply_hash(db_path: Path, mount_root: Path) -> str:
    """Apply the iPod Classic 6G/7G firmware hash to *db_path* in place.

    Returns 'libgpod' or 'builtin' to indicate which method was used.
    Raises RuntimeError if neither method succeeds.
    """
    if _try_libgpod(db_path, mount_root):
        return "libgpod"
    if _try_builtin(db_path, mount_root):
        return "builtin"
    raise RuntimeError(
        "Could not apply iPod Classic hash.\n"
        "Install libgpod to enable full support:\n"
        "  macOS:  brew install libgpod\n"
        "  Linux:  sudo apt install libgpod-dev\n"
        "The iPod may refuse to load music added or removed by this tool."
    )


def read_firewire_guid(mount_root: Path) -> bytes | None:
    """Return the 8-byte FirewireGuid from SysInfo, or None."""
    info = _read_sysinfo(mount_root)
    raw = info.get("FirewireGuid", "").strip()
    if raw.startswith("0x"):
        raw = raw[2:]
    try:
        b = bytes.fromhex(raw.zfill(16))
        return b if any(b) else None
    except ValueError:
        return None


# ── approach 1: libgpod via ctypes ─────────────────────────────────────────

def _try_libgpod(db_path: Path, mount_root: Path) -> bool:
    """Use libgpod's itdb_parse + itdb_write to apply the hash."""
    import ctypes
    import ctypes.util

    lib_name = ctypes.util.find_library("gpod")
    if not lib_name:
        for candidate in _LIBGPOD:
            if Path(candidate).exists():
                lib_name = candidate
                break
    if not lib_name:
        return False

    try:
        lib = ctypes.CDLL(lib_name)
        lib.itdb_parse.restype = ctypes.c_void_p
        lib.itdb_parse.argtypes = [ctypes.c_char_p, ctypes.c_void_p]
        lib.itdb_write.restype = ctypes.c_int
        lib.itdb_write.argtypes = [ctypes.c_void_p, ctypes.c_void_p]
        lib.itdb_free.argtypes = [ctypes.c_void_p]

        db = lib.itdb_parse(str(mount_root).encode(), None)
        if not db:
            return False
        ok = lib.itdb_write(db, None)
        lib.itdb_free(db)
        return bool(ok)
    except (OSError, AttributeError):
        return False


# ── approach 2: pure-Python hash58 ────────────────────────────────────────

def _try_builtin(db_path: Path, mount_root: Path) -> bool:
    """Apply the hash58 algorithm in pure Python."""
    guid = read_firewire_guid(mount_root)
    if not guid:
        return False

    key = _derive_key(guid)
    data = bytearray(db_path.read_bytes())
    if len(data) < _HASH_OFFSET + _HASH_LEN:
        return False

    data[_HASH_OFFSET:_HASH_OFFSET + _HASH_LEN] = b"\x00" * _HASH_LEN
    digest = _hmac.new(key, bytes(data), hashlib.sha1).digest()
    data[_HASH_OFFSET:_HASH_OFFSET + _HASH_LEN] = digest
    db_path.write_bytes(bytes(data))
    return True


def _derive_key(guid: bytes) -> bytes:
    """Derive the 64-byte HMAC key from the 8-byte FirewireGuid.

    Port of libgpod itdb_hash58.c::generate_key().
    The algorithm processes pairs of GUID bytes through LCM and two
    substitution tables to build a 64-byte key block.
    """
    # Pad / truncate guid to exactly 8 bytes
    guid = (guid + b"\x00" * 8)[:8]

    out = bytearray(64)
    for i in range(8):
        a = _T1[guid[i]]
        b = _T2[guid[i]]
        lcm = _lcm(a if a else 1, b if b else 1)
        for j in range(8):
            out[i * 8 + j] = (lcm >> (j * 8)) & 0xFF

    return bytes(out)


def _gcd(a: int, b: int) -> int:
    while b:
        a, b = b, a % b
    return a


def _lcm(a: int, b: int) -> int:
    g = _gcd(a, b)
    return a // g * b if g else 0


# ── helpers ────────────────────────────────────────────────────────────────

def _read_sysinfo(mount_root: Path) -> dict:
    path = mount_root / "iPod_Control" / "Device" / "SysInfo"
    if not path.exists():
        return {}
    result: dict[str, str] = {}
    for line in path.read_text(errors="replace").splitlines():
        k, sep, v = line.partition(":")
        if sep:
            result[k.strip()] = v.strip()
    return result
